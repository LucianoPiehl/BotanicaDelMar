function normalizeWhitespace(value) {
  return String(value ?? "").replace(/\s+/g, " ").trim();
}

function normalizeMeasureToken(value) {
  const match = normalizeWhitespace(value).match(/(\d+(?:[.,]\d+)?)\s*(kg|gr|g|cc|ml)\b/i);
  if (!match) {
    return "";
  }

  let amount = match[1].replace(",", ".");
  if (amount.endsWith(".0")) {
    amount = amount.slice(0, -2);
  }

  const rawUnit = match[2].toLowerCase();
  const unit = rawUnit === "g" ? "gr" : rawUnit === "ml" ? "cc" : rawUnit;
  return `${amount} ${unit}`;
}

function extractFormatLabel(source) {
  const normalized = normalizeWhitespace(source);
  if (/frascos?\s+gotero/iu.test(normalized)) {
    return "Frasco gotero";
  }

  if (/pote/iu.test(normalized)) {
    return "Pote";
  }

  if (/frasco/iu.test(normalized)) {
    return "Frasco";
  }

  return "";
}

function buildPresentationCode(detail, fallbackPresentation = "") {
  const measure = normalizeMeasureToken(detail) || normalizeMeasureToken(fallbackPresentation);
  return measure ? measure.toUpperCase() : normalizeWhitespace(fallbackPresentation).toUpperCase();
}

function buildPresentationDetail(detail, subtitle = "", fallbackPresentation = "", formatHint = "") {
  const format = extractFormatLabel(`${detail} ${subtitle} ${formatHint}`) || "Presentacion";
  const measure = normalizeMeasureToken(detail) || normalizeMeasureToken(fallbackPresentation);
  if (!measure) {
    return normalizeWhitespace(detail || fallbackPresentation);
  }

  return format === "Presentacion" ? measure : `${format} ${measure}`;
}

function cleanSubtitle(subtitle) {
  return normalizeWhitespace(subtitle)
    .split("|")
    .map((segment) => normalizeWhitespace(segment))
    .filter(Boolean)
    .filter((segment) => !/(\d+(?:[.,]\d+)?\s*(kg|gr|g|cc|ml)\b)|\b(frasco|frascos|pote|valvula)\b/iu.test(segment))
    .join(" | ");
}

function createVariantSuffix(detail) {
  return normalizeMeasureToken(detail).replace(/\s+/g, "-");
}

function findPrimaryVariantIndex(product, variants) {
  const targetMeasure = normalizeMeasureToken(product.presentation) || normalizeMeasureToken(product.presentationDetail);
  if (targetMeasure) {
    const exactMatchIndex = variants.findIndex((variant) => normalizeMeasureToken(variant) === targetMeasure);
    if (exactMatchIndex >= 0) {
      return exactMatchIndex;
    }

    const targetAmount = targetMeasure.split(" ")[0];
    const amountMatchIndex = variants.findIndex((variant) => normalizeMeasureToken(variant).startsWith(`${targetAmount} `));
    if (amountMatchIndex >= 0) {
      return amountMatchIndex;
    }
  }

  return variants.length - 1;
}

function normalizeProduct(product) {
  const cleanedSubtitle = cleanSubtitle(product.subtitle);
  const presentationDetail = buildPresentationDetail(
    product.presentationDetail,
    cleanedSubtitle,
    product.presentation,
    product.subtitle,
  );
  return {
    ...product,
    presentation: buildPresentationCode(presentationDetail, product.presentation),
    presentationDetail,
    subtitle: cleanedSubtitle,
  };
}

function expandProducts(products) {
  return products.flatMap((product) => {
    const variants = splitPresentationMap[product.id];
    if (!variants) {
      return [normalizeProduct(product)];
    }

    const cleanedSubtitle = cleanSubtitle(product.subtitle);
    const primaryVariantIndex = findPrimaryVariantIndex(product, variants);

    return variants.map((variant, index) => {
      const presentationDetail = buildPresentationDetail(variant, cleanedSubtitle, product.presentation, product.subtitle);
      const variantSuffix = createVariantSuffix(variant);
      const isPrimaryVariant = index === primaryVariantIndex;

      return {
        ...product,
        id: isPrimaryVariant ? product.id : `${product.id}-${variantSuffix}`,
        slug: isPrimaryVariant ? product.slug : `${product.slug}-${variantSuffix}`,
        presentation: buildPresentationCode(presentationDetail, product.presentation),
        presentationDetail,
        subtitle: cleanedSubtitle,
      };
    });
  });
}

